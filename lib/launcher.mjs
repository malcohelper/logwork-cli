import { spawn } from 'node:child_process';
import { constants as fsConstants, promises as fs } from 'node:fs';
import { posix, win32 } from 'node:path';
import { atomicWriteFile } from './atomic-file.mjs';
import { helperHome } from './paths.mjs';

// IDE MCP configs and the reminder schedule must keep working after nvm,
// Homebrew or a Node installer upgrade, without the user editing anything.
//
// - macOS/Linux: `logwork setup` writes <home>/bin/logwork-launch, a POSIX sh
//   script that finds a usable Node 22+ at start time and runs
//   <home>/bin/logwork.mjs with it. Configs point at the script, which never
//   moves.
// - Windows: GUI clients would need `cmd /c` for a .cmd launcher, so configs
//   use a stable node.exe instead: the nvm-windows symlink when Node runs from
//   an nvm-windows version folder, otherwise the running node.exe (usually
//   C:\Program Files\nodejs\node.exe, which an installer upgrade keeps).

export const LAUNCHER_FILE_NAME = 'logwork-launch';
export const MIN_NODE_MAJOR = 22;
// Makes the launcher print the Node it would use and exit, without starting
// logwork. Used by `logwork doctor`.
export const LAUNCHER_PRINT_NODE_ENV = 'LOGWORK_LAUNCHER_PRINT_NODE';
const ENTRY_RELATIVE = ['bin', 'logwork.mjs'];

export function launcherPath(home = helperHome()) {
  return posix.join(home, 'bin', LAUNCHER_FILE_NAME);
}

export function entryPath(home = helperHome(), platform = process.platform) {
  return pathApi(platform).join(home, ...ENTRY_RELATIVE);
}

// The command every MCP config and the reminder schedule run. MCP args are
// [...argsPrefix, 'mcp'].
// stable: true when the command survives a Node upgrade without re-running
// `logwork setup`.
export function resolveLaunchCommand({
  platform = process.platform,
  home = helperHome(),
  execPath = process.execPath,
  env = process.env
} = {}) {
  if (platform !== 'win32') {
    return {
      command: launcherPath(home),
      argsPrefix: [],
      kind: 'launcher',
      stable: true
    };
  }
  const entry = win32.join(home, ...ENTRY_RELATIVE);
  const symlink = String(readEnv(env, 'NVM_SYMLINK') || '').trim();
  if (symlink && isNvmWindowsNode(execPath, env)) {
    return {
      command: win32.join(symlink, 'node.exe'),
      argsPrefix: [entry],
      kind: 'nvm-symlink',
      stable: true
    };
  }
  return {
    command: String(execPath),
    argsPrefix: [entry],
    kind: 'node',
    stable: isStandardWindowsInstall(execPath)
  };
}

export function mcpArgs(launch) {
  return [...(launch?.argsPrefix || []), 'mcp'];
}

// Node inside an nvm-windows version folder, e.g. C:\Users\me\AppData\Roaming\nvm\v22.11.0\node.exe.
export function isNvmWindowsNode(execPath, env = process.env) {
  const path = String(execPath || '').toLowerCase().replaceAll('/', '\\');
  const nvmHome = String(readEnv(env, 'NVM_HOME') || '').toLowerCase().replaceAll('/', '\\').replace(/\\+$/, '');
  if (nvmHome && path.startsWith(`${nvmHome}\\`)) {
    return true;
  }
  return /\\nvm\\v\d+\.\d+\.\d+[^\\]*\\node\.exe$/.test(path);
}

// The official installer keeps node.exe at <Program Files>\nodejs\node.exe
// across upgrades.
export function isStandardWindowsInstall(execPath) {
  return /\\nodejs\\node\.exe$/i.test(String(execPath || '').replaceAll('/', '\\'));
}

export function buildPosixLauncherScript({ home, nodePath }) {
  const entry = posix.join(home, ...ENTRY_RELATIVE);
  return `#!/bin/sh
# Generated by \`logwork setup\`; it is rewritten on every setup, so do not edit.
# Starts logwork with the first usable Node.js ${MIN_NODE_MAJOR}+, so IDE MCP configs and the
# reminder keep working after nvm, Homebrew or installer upgrades.
LOGWORK_ENTRY=${quoteSh(entry)}
LOGWORK_RECORDED_NODE=${quoteSh(nodePath || '')}

logwork_node_ok() {
  [ -n "$1" ] && [ -f "$1" ] && [ -x "$1" ] || return 1
  "$1" -e 'process.exit(+process.versions.node.split(".")[0]>=${MIN_NODE_MAJOR}?0:1)' >/dev/null 2>&1
}

logwork_run() {
  logwork_node=$1
  shift
  if [ "\${${LAUNCHER_PRINT_NODE_ENV}:-}" = "1" ]; then
    printf '%s\\n' "$logwork_node"
    exit 0
  fi
  exec "$logwork_node" "$LOGWORK_ENTRY" "$@"
}

logwork_newest_nvm_node() {
  logwork_best=''
  logwork_best_key=0
  for logwork_dir in "$@"; do
    [ -n "$logwork_dir" ] && [ -d "$logwork_dir/versions/node" ] || continue
    for logwork_candidate in "$logwork_dir"/versions/node/v*/bin/node; do
      [ -x "$logwork_candidate" ] || continue
      logwork_version=\${logwork_candidate%/bin/node}
      logwork_version=\${logwork_version##*/v}
      logwork_major=\${logwork_version%%.*}
      logwork_rest=\${logwork_version#*.}
      logwork_minor=\${logwork_rest%%.*}
      logwork_patch=\${logwork_rest#*.}
      logwork_patch=\${logwork_patch%%[!0-9]*}
      case "$logwork_major.$logwork_minor.$logwork_patch" in
        *[!0-9.]*|.*|*..*|*.) continue ;;
      esac
      [ "$logwork_major" -ge ${MIN_NODE_MAJOR} ] || continue
      logwork_key=$((logwork_major * 1000000 + logwork_minor * 1000 + logwork_patch))
      if [ "$logwork_key" -gt "$logwork_best_key" ]; then
        logwork_best=$logwork_candidate
        logwork_best_key=$logwork_key
      fi
    done
  done
  printf '%s' "$logwork_best"
}

# 1. The Node recorded by setup. Its path names its version, so an existing
#    file is still that Node: skip the version check for a fast start.
if [ -n "$LOGWORK_RECORDED_NODE" ] && [ -f "$LOGWORK_RECORDED_NODE" ] && [ -x "$LOGWORK_RECORDED_NODE" ]; then
  logwork_run "$LOGWORK_RECORDED_NODE" "$@"
fi

# 2. node on PATH.
logwork_candidate=$(command -v node 2>/dev/null || true)
if logwork_node_ok "$logwork_candidate"; then
  logwork_run "$logwork_candidate" "$@"
fi

# 3. The newest nvm Node ${MIN_NODE_MAJOR}+.
logwork_candidate=$(logwork_newest_nvm_node "\${NVM_DIR:-}" "\${HOME:-}/.nvm")
if logwork_node_ok "$logwork_candidate"; then
  logwork_run "$logwork_candidate" "$@"
fi

# 4. Volta and fnm defaults, then 5. Homebrew and /usr/local.
for logwork_candidate in \\
  "\${HOME:-}/.volta/bin/node" \\
  "\${HOME:-}/.local/share/fnm/aliases/default/bin/node" \\
  "\${HOME:-}/Library/Application Support/fnm/aliases/default/bin/node" \\
  /opt/homebrew/bin/node \\
  /usr/local/bin/node
do
  if logwork_node_ok "$logwork_candidate"; then
    logwork_run "$logwork_candidate" "$@"
  fi
done

echo "logwork: no usable Node.js ${MIN_NODE_MAJOR}+ found. Install Node.js ${MIN_NODE_MAJOR} or newer, or run \\\`logwork setup\\\` again." >&2
exit 127
`;
}

// Writes the launcher on macOS/Linux. A no-op on Windows (returns null).
export async function writeLauncher({
  home = helperHome(),
  nodePath = process.execPath,
  platform = process.platform,
  writeFile = atomicWriteFile,
  chmod = fs.chmod
} = {}) {
  if (platform === 'win32') {
    return null;
  }
  const path = launcherPath(home);
  await writeFile(path, buildPosixLauncherScript({ home, nodePath }), { mode: 0o755 });
  // atomicWriteFile applies the mode through the umask; make it explicit.
  await chmod(path, 0o755);
  return { path, nodePath };
}

// Checks the command MCP configs and the reminder run. Read-only: it runs the
// command with `--version` (which prints the logwork version through
// bin/logwork.mjs) and, for the launcher, asks which Node it would pick.
export async function checkLaunchCommand(launch = resolveLaunchCommand(), {
  platform = process.platform,
  access = fs.access,
  run = runProcess,
  env = process.env
} = {}) {
  const result = {
    command: launch.command,
    kind: launch.kind,
    status: 'ok',
    node: launch.kind === 'launcher' ? '' : launch.command,
    version: ''
  };
  try {
    await access(launch.command, fsConstants.F_OK);
  } catch {
    return { ...result, status: 'missing' };
  }
  if (platform !== 'win32') {
    try {
      await access(launch.command, fsConstants.X_OK);
    } catch {
      return { ...result, status: 'not_executable' };
    }
  }
  const childEnv = withoutLogworkEnv(env);
  if (launch.kind === 'launcher') {
    const picked = await run(launch.command, [], { env: { ...childEnv, [LAUNCHER_PRINT_NODE_ENV]: '1' } }).catch((error) => ({ code: 1, stdout: '', stderr: error.message }));
    if (picked.code !== 0) {
      return { ...result, status: 'no_node', detail: firstLine(picked.stderr || picked.stdout) };
    }
    result.node = firstLine(picked.stdout);
  }
  const version = await run(launch.command, [...launch.argsPrefix, '--version'], { env: childEnv }).catch((error) => ({ code: 1, stdout: '', stderr: error.message }));
  if (version.code !== 0) {
    return { ...result, status: 'failed', detail: firstLine(version.stderr || version.stdout) };
  }
  result.version = firstLine(version.stdout);
  return result;
}

export function formatLaunchCheckIssue(check) {
  switch (check?.status) {
    case 'missing':
      return check.kind === 'launcher'
        ? `Launcher: ${check.command} is missing, so IDE MCP configs and the reminder cannot start. Fix: run \`logwork setup\`.`
        : `Node: ${check.command} no longer exists, so IDE MCP configs and the reminder cannot start. Fix: run \`logwork setup\`.`;
    case 'not_executable':
      return `Launcher: ${check.command} is not executable. Fix: run \`logwork setup\`.`;
    case 'no_node':
      return `Launcher: found no usable Node.js ${MIN_NODE_MAJOR}+. Fix: install Node.js ${MIN_NODE_MAJOR} or newer, then run \`logwork setup\`.`;
    case 'failed':
      return `Launcher: ${check.command} --version failed${check.detail ? ` (${check.detail})` : ''}. Fix: run \`logwork setup\`.`;
    default:
      return '';
  }
}

export function runProcess(command, args, { env = process.env, cwd } = {}) {
  return new Promise((resolveValue, reject) => {
    const child = spawn(command, args, {
      cwd,
      env,
      stdio: ['ignore', 'pipe', 'pipe'],
      windowsHide: true
    });
    let stdout = '';
    let stderr = '';
    child.stdout.setEncoding('utf8');
    child.stderr.setEncoding('utf8');
    child.stdout.on('data', (chunk) => { stdout += chunk; });
    child.stderr.on('data', (chunk) => { stderr += chunk; });
    child.on('error', reject);
    child.on('close', (code, signal) => resolveValue({ code: signal ? 1 : (code ?? 1), stdout, stderr }));
  });
}

export function pathApi(platform = process.platform) {
  return platform === 'win32' ? win32 : posix;
}

// The launcher must not inherit a test or dev LOGWORK_HOME that points at a
// different runtime than the one it launches.
function withoutLogworkEnv(env) {
  return Object.fromEntries(Object.entries(env || {}).filter(([key]) => !key.startsWith('LOGWORK_')));
}

function firstLine(value) {
  return String(value || '').trim().split(/\r?\n/)[0] || '';
}

function quoteSh(value) {
  return `'${String(value).replaceAll("'", "'\\''")}'`;
}

function readEnv(env, name) {
  if (!env) {
    return undefined;
  }
  if (env[name] !== undefined) {
    return env[name];
  }
  const key = Object.keys(env).find((item) => item.toUpperCase() === name);
  return key ? env[key] : undefined;
}
